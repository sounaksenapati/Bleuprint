"use client";

import { useWorkspaceStore } from "@/store/workspace-store";
import { ChatInterface } from "./ChatInterface";
import { ViewerTabs } from "./ViewerTabs";
import { ConstraintPanel } from "./ConstraintPanel";
import { Button } from "@/components/ui/button";
import { Cpu, Download, Share2 } from "lucide-react";
import Link from "next/link";
import { toast } from "sonner";
import {
  ResizableHandle,
  ResizablePanel,
  ResizablePanelGroup,
} from "@/components/ui/resizable";

export function WorkspaceLayout({ projectId }: { projectId: string }) {
  const { project, constraints, artifacts } = useWorkspaceStore();

  async function handleExport() {
    try {
      const JSZip = (await import("jszip")).default;
      const zip = new JSZip();

      if (artifacts.prd) zip.file("prd.json", artifacts.prd);
      if (artifacts.cad) zip.file("cad/enclosure.scad", artifacts.cad);
      if (artifacts.firmware) zip.file("firmware/main.cpp", artifacts.firmware);
      if (artifacts.bom) zip.file("electronics/bom.csv", artifacts.bom);

      if (constraints) {
        zip.file(
          "README.md",
          `# ${constraints.product_name}\n\n${constraints.description}\n\n## Generated by Blueprint\n\nThis project was generated using Blueprint - the AI-native hardware development platform.\n\n## Files\n- \`prd.json\` - Product Requirements Document\n- \`cad/enclosure.scad\` - OpenSCAD 3D model\n- \`firmware/main.cpp\` - Firmware source code\n- \`electronics/bom.csv\` - Bill of Materials\n`
        );
      }

      const blob = await zip.generateAsync({ type: "blob" });
      const url = URL.createObjectURL(blob);
      const a = document.createElement("a");
      a.href = url;
      a.download = `${project?.name || "blueprint-project"}.zip`;
      a.click();
      URL.revokeObjectURL(url);
      toast.success("Project exported successfully!");
    } catch {
      toast.error("Failed to export project");
    }
  }

  return (
    <div className="flex h-full flex-col">
      {/* Top bar */}
      <div className="flex h-12 items-center justify-between border-b border-border/50 px-4">
        <div className="flex items-center gap-3">
          <Link href="/projects" className="flex items-center gap-2">
            <Cpu className="h-4 w-4 text-primary" />
          </Link>
          <span className="text-sm font-semibold">
            {project?.name || "Untitled Project"}
          </span>
        </div>
        <div className="flex items-center gap-2">
          <Button
            variant="ghost"
            size="sm"
            className="gap-1.5"
            onClick={() => {
              navigator.clipboard.writeText(window.location.href);
              toast.success("Link copied!");
            }}
          >
            <Share2 className="h-3.5 w-3.5" />
            Share
          </Button>
          <Button
            variant="ghost"
            size="sm"
            className="gap-1.5"
            onClick={handleExport}
          >
            <Download className="h-3.5 w-3.5" />
            Export
          </Button>
        </div>
      </div>

      {/* Main workspace */}
      <div className="flex-1 overflow-hidden">
        <ResizablePanelGroup direction="horizontal">
          <ResizablePanel defaultSize={25} minSize={15}>
            <ChatInterface projectId={projectId} />
          </ResizablePanel>
          <ResizableHandle withHandle />
          <ResizablePanel defaultSize={50} minSize={30}>
            <ViewerTabs />
          </ResizablePanel>
          <ResizableHandle withHandle />
          <ResizablePanel defaultSize={25} minSize={15}>
            <ConstraintPanel projectId={projectId} />
          </ResizablePanel>
        </ResizablePanelGroup>
      </div>
    </div>
  );
}
